/**
 * THE ICON SET, AS PIXEL ART.
 *
 * Every glyph is 16 rows of 16 characters:
 *
 *   "."  transparent
 *   "x"  ink, full strength
 *   "o"  ink at half strength, for a second tone inside one colour
 *
 * WHY A CHARACTER GRID RATHER THAN SVG PATHS. The previous icons were 24x24
 * strokes with round caps at 2.5px - a perfectly good web-app idiom, and
 * completely wrong for chunky pixel art: a stroked path antialiases, so at any
 * size the "pixels" have soft grey edges. These are rectangles on an integer
 * grid, and they are drawn with shapeRendering="crispEdges", so an icon is made
 * of the same hard pixels the game world is.
 *
 * Being able to READ the picture in the source is the point. A young player
 * could redraw one of these by typing an x, which is not true of "M12 2L3 9.5".
 *
 * THE SIZE RULE. A glyph is 16 units wide, so it must be rendered at a multiple
 * of 16 CSS pixels. At 24px each glyph pixel would be 1.5 screen pixels and
 * adjacent pixels would come out 1px and 2px wide alternately - which looks
 * subtly broken in a way that passes every automated check. SIZE.iconLarge and
 * SIZE.iconSmall exist as multiples of 16 for exactly this reason, and Icon.tsx
 * warns in development if it is handed anything else.
 */

