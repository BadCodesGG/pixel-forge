/** One horizontal run of identical pixels: the unit an icon is drawn in. */
export interface GlyphRun {
  x: number;
  y: number;
  w: number;
  /** True for "o" - the half-strength tone. */
  soft: boolean;
}

/**
 * Collapse a glyph into horizontal runs.
 *
 * A 16x16 glyph is up to 256 rectangles drawn one pixel at a time; merging runs
 * takes a typical glyph down to 20-40. Cheap to compute and computed once per
 * glyph per session, so the saving is pure.
 */
export function glyphRuns(rows: readonly string[]): GlyphRun[] {
  const runs: GlyphRun[] = [];
  for (let y = 0; y < rows.length; y++) {
    const row = rows[y];
    let x = 0;
    while (x < row.length) {
      const ch = row[x];
      if (ch === ".") {
        x++;
        continue;
      }
      let end = x;
      while (end < row.length && row[end] === ch) end++;
      runs.push({ x, y, w: end - x, soft: ch === "o" });
      x = end;
    }
  }
  return runs;
}
